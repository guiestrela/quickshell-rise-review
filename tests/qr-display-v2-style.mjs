import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = p => fs.readFileSync(new URL('../'+p, import.meta.url), 'utf8');
const variant = read('versions/V1/variants/V2/VariantRoot.qml');
assert.match(variant, /(?<!\.)\bDisplayManagerPanel\s*\{\s*root:\s*theme/, 'V2 must load its native-style wrapper, not the plain shared panel');
const wrapper = read('versions/V1/variants/V2/panels/DisplayManagerPanel.qml');
assert.match(wrapper, /Shared\.DisplayManagerPanel/);
assert.match(wrapper, /connectedStyle:\s*true/);
assert.match(wrapper, /ConnectedPanelSurface/);
assert.match(wrapper, /parent:\s*panel\.surfaceHost/);
assert.match(wrapper, /targetX:\s*panel\.root\.displayManagerBarX/);
assert.match(wrapper, /reveal:\s*panel\.root\.panelInsetReveal/);
const theme = read('versions/V1/variants/V2/Theme.qml');
const anchored = theme.match(/readonly property bool anchoredPanelVisible:([\s\S]*?)\n\s*\/\//)[1];
assert.match(anchored, /displayManagerVisible/, 'Display Manager must participate in the native bar notch');
const panel = read('versions/V1/panels/DisplayManagerPanel.qml');
assert.match(panel, /readonly property Item surfaceHost:/);
assert.match(panel, /color: panel\.connectedStyle \? "transparent" : panel\.root\.bg/);
assert.match(panel, /border\.width: panel\.connectedStyle \? 0 : panel\.root\.pillBorderW/);
assert.match(wrapper, /headerComponent:\s*Component/, 'V2 header must match the NordVPN reference, not the large shared header');
assert.match(wrapper, /font\.pixelSize:\s*13/);
assert.match(wrapper, /font\.letterSpacing:\s*2/);
assert.match(wrapper, /Native\.UiText/);
assert.match(wrapper, /objectName:\s*"display-v2-close"/);
assert.match(panel, /visible:\s*!panel\.connectedStyle/);
console.log('DISPLAY_V2_STYLE_CONTRACT_PASS native surface, notch and NordVPN header; source assertions only');
